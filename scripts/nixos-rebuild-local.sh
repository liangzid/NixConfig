#!/usr/bin/env bash
set -euo pipefail

# ======================================================================
# NIXOS-REBUILD-LOCAL
#
# 1. Flake 在 git 仓库内只看见「已跟踪/已暂存」文件；gitignore 的
#    hardware-configuration.nix 和 detected-memory.nix 必须临时
#    git add -f，求值完再 unstage。
# 2. 调用链：update/upgrade 别名 → 本脚本 → nixos-rebuild
# 3. 修改历史：
#      2026-08-20 创建：修正「仅 path: 即可」的错误假设。
#      2026-11-24 从 /proc/meminfo 写出 detected-memory.nix（Nix 读不了
#                 /proc），供 max-jobs/cores 按本机 RAM 计算。
#
#     Author: Zi Liang <zi1415926.liang@connect.polyu.hk>
#     Copyright © 2026, Zi Liang, all rights reserved.
#     Created: 20 August 2026
# ======================================================================

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
HW_FILE="$REPO_DIR/hosts/nixos/hardware-configuration.nix"
MEM_FILE="$REPO_DIR/hosts/nixos/detected-memory.nix"
FLAKE_ATTR="${FLAKE_ATTR:-nixos}"

if [[ ! -f "$HW_FILE" ]]; then
  echo "错误: 缺少本机 $HW_FILE" >&2
  echo "请先生成: sudo nixos-generate-config --show-hardware-config" >&2
  echo "或: sudo nixos-generate-config --root / && cp /etc/nixos/hardware-configuration.nix $HW_FILE" >&2
  exit 1
fi

# Nix builtins.readFile 读不了 /proc/meminfo（纯求值禁止；impure 也是空串）。
# 由 shell 写出给 flake；读失败则不写文件，Nix 侧按 16GiB 兜底。
write_detected_memory() {
  local mem_kb
  mem_kb="$(awk '/^MemTotal:/ { print $2; exit }' /proc/meminfo)"
  if [[ ! "$mem_kb" =~ ^[0-9]+$ ]]; then
    echo "警告: 读不到 /proc/meminfo 的 MemTotal，Nix 将按 16GiB 兜底。" >&2
    return 0
  fi
  cat > "$MEM_FILE" <<EOF
# Generated by scripts/nixos-rebuild-local.sh from /proc/meminfo. Do not edit.
{ totalMemKb = ${mem_kb}; }
EOF
  git -C "$REPO_DIR" add -f "$MEM_FILE"
  echo "detected MemTotal=${mem_kb} kB"
}

# 临时纳入 index，供 flake 看见；结束后撤掉暂存，文件仍留在磁盘且保持 ignore。
git -C "$REPO_DIR" add -f "$HW_FILE"
write_detected_memory
cleanup() {
  git -C "$REPO_DIR" restore --staged "$HW_FILE" 2>/dev/null || true
  git -C "$REPO_DIR" restore --staged "$MEM_FILE" 2>/dev/null || true
}
trap cleanup EXIT

# 当前 nix-daemon 仍是旧的 max-jobs=8 / MemoryMax=infinity，必须在本次
# switch 的编译阶段就限住，否则还没激活新配置就已经 OOM。
# MemoryHigh/Max 百分数与 configuration.nix 保持一致。
HOST_MEM_JSON="$(nix-instantiate --eval --strict --json -E \
  "import $REPO_DIR/modules/lib/host-memory.nix { hostDir = $REPO_DIR/hosts/nixos; }")"
MAX_JOBS="$(sed -n 's/.*"maxJobs":\([0-9]*\).*/\1/p' <<<"$HOST_MEM_JSON")"
CORES="$(sed -n 's/.*"cores":\([0-9]*\).*/\1/p' <<<"$HOST_MEM_JSON")"
if [[ ! "$MAX_JOBS" =~ ^[0-9]+$ || ! "$CORES" =~ ^[0-9]+$ ]]; then
  echo "错误: 无法从 host-memory.nix 解析 max-jobs/cores: $HOST_MEM_JSON" >&2
  exit 1
fi
echo "nix build limits from host-memory.nix: $HOST_MEM_JSON"

sudo systemctl set-property --runtime nix-daemon.service \
  MemoryHigh=50% MemoryMax=70% || true

if [[ $# -eq 0 ]]; then
  set -- switch
fi

sudo nixos-rebuild "$@" --flake "$REPO_DIR#$FLAKE_ATTR" \
  --option max-jobs "$MAX_JOBS" --option cores "$CORES"
